// Generator for lib/blog/registry.generated.ts (spec 2.4, 5, R14).
//
// lib/pages.ts must not read the filesystem at import time, so the published
// articles are baked into a static TS module by `npm run blog:registry`
// (scripts/blog/build-registry.mjs). This file is the pure logic behind it, so a
// jest test can regenerate the module in memory and compare it with the committed file.
// It is never imported by lib/pages.ts (only the generated module is).

import { join } from 'path';
import { existsSync } from 'fs';
import { buildStats, gapOf } from './stats';
import { generatedTitle, articleLabel } from './title';
import { renderTokens } from './tokens';
import { loadArticleFiles, loadFilms } from './load';
import type { Article, Film } from './types';

/** Shape of one entry in registry.generated.ts. Scores feed llms-full.txt (spec 5). */
export interface BlogArticlePageData {
  path: string;
  /** R7 generated title, without the site suffix. */
  title: string;
  /** Description with tokens rendered. */
  description: string;
  /** YYYY-MM-DD */
  published: string;
  /** YYYY-MM-DD: max(published, contentUpdated, film.dataChangedAt) (R14). */
  updated: string;
  /** `{Title} ({Year})` */
  label: string;
  scores: { imdb: number; rt: number; gap: number; /** YYYY-MM-DD of the OMDb fetch */ asOf: string };
  /** IMDb id of the film, so other pages can link a published analysis by id (I8). */
  imdbId: string;
}

/**
 * Hub state baked into the registry (I9, I10). The /blog hub is public (registered, prerendered,
 * linked from other pages) only when `ready`: films.json exists and holds exactly the expected
 * number of films. `dataUpdated` is max(films[].dataChangedAt) and feeds the hub lastmod.
 */
export interface BlogHubStateData {
  ready: boolean;
  /** YYYY-MM-DD, or null without films.json. */
  dataUpdated: string | null;
}

export const HUB_NOT_READY: BlogHubStateData = { ready: false, dataUpdated: null };

/** Films the hub needs before it goes public. Fixture builds lower it with BLOG_EXPECT_FILMS. */
export const DEFAULT_EXPECT_FILMS = 100;

export function expectedFilmCount(env: Record<string, string | undefined> = process.env): number {
  const raw = env.BLOG_EXPECT_FILMS?.trim();
  if (!raw) return DEFAULT_EXPECT_FILMS;
  const n = Number(raw);
  if (!Number.isInteger(n) || n < 1) throw new Error(`BLOG_EXPECT_FILMS must be a positive integer (got "${raw}")`);
  return n;
}

/** Hub state for a films list (null = no films.json). */
export function hubState(films: Film[] | null, expectFilms: number): BlogHubStateData {
  if (!films) return HUB_NOT_READY;
  const dataUpdated = films.reduce<string | null>((max, f) => (max === null || f.dataChangedAt > max ? f.dataChangedAt : max), null);
  return { ready: films.length === expectFilms, dataUpdated };
}

export const REGISTRY_RELATIVE_PATH = 'lib/blog/registry.generated.ts';
export const registryFilePath = (root: string = process.cwd()): string => join(root, REGISTRY_RELATIVE_PATH);

const maxDate = (...dates: string[]): string => dates.reduce((a, b) => (b > a ? b : a));

/** One entry per article with status "published", ordered by film popularity rank. */
export function buildRegistryEntries(films: Film[], articles: Article[]): BlogArticlePageData[] {
  const published = articles.filter((a) => a.status === 'published');
  if (published.length === 0) return [];
  const bySlug = new Map(films.map((f) => [f.slug, f]));
  const stats = buildStats(films);
  const rows = published.map((article) => {
    const film = bySlug.get(article.slug);
    if (!film) throw new Error(`registry: published article "${article.slug}" has no film in films.json`);
    if (!article.published) throw new Error(`registry: published article "${article.slug}" has no "published" date`);
    const description = renderTokens(article.description, { film, stats: stats[film.slug], sources: article.sources });
    const entry: BlogArticlePageData = {
      path: `/blog/${article.slug}`,
      title: generatedTitle(film, article.shortTitle).title,
      description,
      published: article.published,
      updated: maxDate(article.published, article.contentUpdated, film.dataChangedAt),
      label: articleLabel(film),
      scores: {
        imdb: film.omdb.imdbRating,
        rt: film.omdb.rtPercent,
        gap: gapOf(film),
        asOf: film.fetchedAt.slice(0, 10),
      },
      imdbId: film.omdb.imdbId,
    };
    return { rank: film.popularityRank, entry };
  });
  return rows.sort((a, b) => a.rank - b.rank || a.entry.path.localeCompare(b.entry.path)).map((r) => r.entry);
}

const HEADER = `// GENERATED by \`npm run blog:registry\` (scripts/blog/build-registry.mjs). Do not edit by hand.
// One entry per published blog article. lib/pages.ts reads this static module so it never
// touches the filesystem at import time. tests/blog/registry.test.ts fails when it is stale.

export interface BlogArticlePage {
  path: string;
  title: string;
  description: string;
  published: string;
  updated: string;
  label: string;
  scores: { imdb: number; rt: number; gap: number; asOf: string };
  imdbId: string;
}

/** The /blog hub is public only when ready (films.json holds the expected film count). */
export interface BlogHubState {
  ready: boolean;
  dataUpdated: string | null;
}

`;

export function renderRegistryModule(entries: readonly BlogArticlePageData[], hub: BlogHubStateData = HUB_NOT_READY): string {
  const body = entries.length === 0 ? '[]' : JSON.stringify(entries, null, 2);
  const hubBody = JSON.stringify({ ready: hub.ready, dataUpdated: hub.dataUpdated }, null, 2);
  return `${HEADER}export const BLOG_HUB: BlogHubState = ${hubBody};\n\nexport const BLOG_ARTICLE_PAGES: readonly BlogArticlePage[] = ${body};\n`;
}

/**
 * Full regeneration from the blog data directory (`dataDir`, default `{root}/data/blog`).
 * No films.json gives a hub that is not ready; with no published articles the entry list is
 * empty. A published article while the hub is not ready is an error: it would link a 404 hub.
 */
export function generateRegistrySource(opts: { root?: string; dataDir?: string; expectFilms?: number } = {}): string {
  const root = opts.root ?? process.cwd();
  const dataDir = opts.dataDir ?? join(root, 'data/blog');
  const articlesDir = join(dataDir, 'articles');
  const filmsPath = join(dataDir, 'films.json');
  const films = existsSync(filmsPath) ? loadFilms(filmsPath) : null;
  const hub = hubState(films, opts.expectFilms ?? expectedFilmCount());
  const published = existsSync(articlesDir)
    ? loadArticleFiles(articlesDir)
        .map((f) => f.article)
        .filter((a) => a.status === 'published')
    : [];
  if (published.length === 0) return renderRegistryModule([], hub);
  if (!hub.ready || !films) {
    throw new Error(
      `${published.length} published article(s) but the hub is not ready (films.json ${films ? `has ${films.length} films, expected ${opts.expectFilms ?? expectedFilmCount()}` : 'is missing'})`,
    );
  }
  return renderRegistryModule(buildRegistryEntries(films, published), hub);
}
